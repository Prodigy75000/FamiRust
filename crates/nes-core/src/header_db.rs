//! iNES header-correction database.
//!
//! Old dump sets (the euroemu/GoodNES-era `.nes` files a lot of libraries are
//! built from) frequently carry the WRONG mapper number in the iNES header —
//! e.g. dozens of UNROM (mapper 2) games tagged as GxROM (mapper 66). The header
//! is just metadata bolted onto the ROM by the dumper; the silicon is whatever it
//! is. Emulators that boot these games (Nestopia, Mesen) do it by overriding the
//! header from an internal database keyed on the ROM's checksum. We do the same.
//!
//! We key on the CRC32 of the ROM DATA — everything after the 16-byte iNES header
//! (trainer + PRG + CHR) — so the fix is header-independent: a re-headered copy of
//! the same cart still matches. Entries are produced by the `gen_header_db` dev
//! bin, which boot-verifies each correction against this very core (it renders
//! under the corrected mapper and not under the header's), so the table is our own
//! empirical measurement, not a copy of anyone else's database.

/// CRC32 (IEEE 802.3, polynomial 0xEDB88320) of the cart data: the bytes after
/// the 16-byte iNES header. Bit-serial — run once at load, ROM-sized, negligible.
pub fn rom_data_crc32(rom: &[u8]) -> u32 {
    let data = if rom.len() > 16 { &rom[16..] } else { &[][..] };
    let mut crc = 0xffff_ffffu32;
    for &b in data {
        crc ^= b as u32;
        for _ in 0..8 {
            let mask = (crc & 1).wrapping_neg();
            crc = (crc >> 1) ^ (0xedb8_8320 & mask);
        }
    }
    !crc
}

use crate::cart::Mirroring;

/// A per-cart header override. Every field is applied only when `Some`; `None`
/// leaves the header's own value untouched. This is the whole cart configuration
/// the iNES header can get wrong — not just the mapper but mirroring, the RAM
/// sizes, and the battery flag — so the DB can correct all of it by checksum.
/// (Submapper is intentionally absent until a mapper actually differentiates on
/// it; there's no point storing data nothing reads.)
#[derive(Clone, Copy)]
pub struct HeaderFix {
    pub mapper: Option<u16>,
    pub mirroring: Option<Mirroring>,
    pub prg_ram: Option<usize>,
    pub chr_ram: Option<usize>,
    pub battery: Option<bool>,
}

impl HeaderFix {
    const EMPTY: HeaderFix = HeaderFix {
        mapper: None,
        mirroring: None,
        prg_ram: None,
        chr_ram: None,
        battery: None,
    };
    /// The common case: correct only the mapper number.
    const fn mapper(m: u16) -> HeaderFix {
        HeaderFix { mapper: Some(m), ..HeaderFix::EMPTY }
    }
}

/// The header correction for a cart whose iNES header is known-wrong, or `None`
/// to trust the header. Looked up by [`rom_data_crc32`].
pub fn correction(data_crc: u32) -> Option<&'static HeaderFix> {
    HEADER_FIXES
        .binary_search_by_key(&data_crc, |&(crc, _)| crc)
        .ok()
        .map(|i| &HEADER_FIXES[i].1)
}

/// `(rom-data CRC32, HeaderFix)`, sorted by CRC for binary search. The mapper
/// entries are GENERATED by the `gen_header_db` bin (boot-verified); richer
