#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn crc32_known_vector() {
        // CRC32 of the ASCII "123456789" is the standard 0xCBF43926. Our function
        // skips the first 16 bytes, so prepend a 16-byte dummy header.
        let mut buf = vec![0u8; 16];
        buf.extend_from_slice(b"123456789");
        assert_eq!(rom_data_crc32(&buf), 0xcbf4_3926);
    }

    #[test]
    fn table_is_sorted_and_searchable() {
        // Binary search requires the table stay sorted by CRC; guard it.
        for w in HEADER_FIXES.windows(2) {
            assert!(w[0].0 < w[1].0, "HEADER_FIXES must be sorted by CRC, ascending");
        }
        for &(crc, fix) in HEADER_FIXES {
            assert_eq!(correction(crc).map(|f| f.mapper), Some(fix.mapper));
        }
        assert!(correction(0x0000_0000).is_none(), "unknown CRC must not match");
    }

    #[test]
    fn richer_fix_carries_all_fields() {
        // The record can express more than the mapper (this is the step-2 point).
        let fix = HeaderFix {
            mapper: Some(1),
            mirroring: Some(Mirroring::Vertical),
            prg_ram: Some(32 * 1024),
            chr_ram: None,
            battery: Some(true),
        };
        assert_eq!(fix.mapper, Some(1));
        assert_eq!(fix.mirroring, Some(Mirroring::Vertical));
        assert_eq!(fix.prg_ram, Some(32 * 1024));
        assert_eq!(fix.battery, Some(true));
        // mapper-only helper leaves the rest untouched.
        let m = HeaderFix::mapper(2);
        assert_eq!(m.mapper, Some(2));
        assert!(m.mirroring.is_none() && m.prg_ram.is_none() && m.battery.is_none());
    }
}
