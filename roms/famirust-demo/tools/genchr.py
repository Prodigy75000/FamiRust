def pad(rows):
    out = []
    for r in rows:
        r = r.replace('0', '.')
        if len(r) > 8:
            raise SystemExit("row too wide: %r" % r)
        out.append((r + "........")[:8])
    while len(out) < 8:
        out.append("........")
    if len(out) != 8:
        raise SystemExit("tile has %d rows" % len(out))
    return out


def emit(w, label, rows, comment=None):
    w.write(".tile %s\n" % label if label else ".tile\n")
    if comment:
        pass
    for r in pad(rows):
        w.write(r + "\n")
    w.write(".endtile\n")


w = io.StringIO()
